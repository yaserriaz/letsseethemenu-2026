/**
 * Build a clean public URL for a blog post.
 */
function blog_post_url(array $post): string
{
    $cat = $post['category_slug'] ?? '';
    $slug = $post['slug'] ?? '';
    if ($cat !== '' && $slug !== '') {
        return 'category/' . rawurlencode($cat) . '/post/' . rawurlencode($slug);
    }
    return 'blog';
}

/**
 * Build a clean public URL for a blog category.
 */
function blog_category_url(string $category_slug): string
{
    return 'category/' . rawurlencode($category_slug);
}
